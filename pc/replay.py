"""Replay a recorded run (runs/<run>/stream.gmtp) or the synthetic sample through the same Pipeline.

  python pc/replay.py samples/synthetic_run                 # summary only, as fast as possible
  python pc/replay.py runs/<run> --speed 1 --log            # real-time pacing, write a new run log
  python pc/viewer.py --replay samples/synthetic_run        # same data in the viewer
  python pc/replay.py --make-synthetic samples/synthetic_run

The synthetic run is generated, not recorded: HELLO says device_id "synthetic". It contains one
missing DETECTIONS record and one dropped frame_id on purpose, so those counters can be checked.
"""
import argparse
import json
import sys
import time
from pathlib import Path

import cv2
import numpy as np

import protocol as P
from heatmap import COLS, ROWS, presence_add
from pipeline import Pipeline


def stream_path(path):
    p = Path(path)
    return p / "stream.gmtp" if p.is_dir() else p


def read_records(path):
    parser = P.Parser()
    with open(stream_path(path), "rb") as f:
        while chunk := f.read(65536):
            yield from parser.feed(chunk)


def paced(records, speed):
    """Sleep between records according to their device timestamps (speed 0 = no pacing)."""
    t0_dev = t0_host = None
    for r in records:
        if speed > 0:
            if t0_dev is None:
                t0_dev, t0_host = r.t_dev_us, time.monotonic()
            wait = (r.t_dev_us - t0_dev) / 1e6 / speed - (time.monotonic() - t0_host)
            if wait > 0:
                time.sleep(min(wait, 2.0))
        yield r


def replay(path, pipeline, speed=0.0):
    for r in paced(read_records(path), speed):
        pipeline.feed(r, P.HDR.size + len(r.payload) + 4)


# ---------------------------------------------------------------- synthetic sample

def make_synthetic(out_dir, seconds=10, fps=7, seed=1):
    """Three box-shaped 'walkers' crossing a 320x240 image. Deterministic."""
    rng = np.random.default_rng(seed)
    w, h = 320, 240
    walkers = [((-30, 200), (350, 170)), ((330, 120), (-20, 150)), ((150, 245), (190, 90))]  # start -> end (feet)
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    seq = 0
    recs = []

    def emit(typ, t_dev_us, payload, frame_id=0):
        nonlocal seq
        recs.append(P.encode(typ, seq, frame_id, t_dev_us, payload))
        seq += 1

    hello = {"proto_version": 1, "device_id": "synthetic", "fw_version": "synthetic", "synthetic": True,
             "sensor_pid": "n/a", "grid_cols": COLS, "grid_rows": ROWS, "box_coords": "frame_px",
             "config": {"mode": "full_stream", "frame_size": "QVGA", "jpeg_quality": 60, "metrics_interval_ms": 1000,
                        "grid_every_n": 10}}
    emit(P.HELLO, 0, json.dumps(hello).encode())
    emit(P.EVENT, 0, json.dumps({"severity": "info", "code": "synthetic_run",
                                 "text": "generated by pc/replay.py, not a recording", "t_event_us": 0}).encode())
    counts = np.zeros((ROWS, COLS), dtype=np.int64)
    n = seconds * fps
    sent = 0
    for i in range(n):
        fid = i + 1
        t_us = 1_000_000 + i * 1_000_000 // fps
        img = np.full((h, w, 3), 90, np.uint8)
        img[h // 2:] = 120  # "floor"
        cv2.putText(img, "SYNTHETIC", (8, 20), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (255, 255, 255), 1)
        boxes = []
        for k, ((x0, y0), (x1, y1)) in enumerate(walkers):
            a = i / (n - 1)
            fx, fy = x0 + (x1 - x0) * a, y0 + (y1 - y0) * a
            bh = int(40 + 70 * fy / h)  # bigger when closer (fake perspective)
            bw = bh // 3
            box = [int(fx - bw / 2), int(fy - bh), int(fx + bw / 2), int(fy)]
            cv2.rectangle(img, (box[0], box[1]), (box[2], box[3]), (40, 40 + 60 * k, 160), -1)
            if 0 <= fx < w and 0 <= fy - 5 < h and not (k == 0 and i == 20):  # walker 0 missed on frame 20
                boxes.append({"x1": max(box[0], 0), "y1": max(box[1], 0), "x2": min(box[2], w - 1),
                              "y2": min(box[3], h - 1), "score": float(0.75 + 0.2 * rng.random())})
        if fid == 40:
            continue  # dropped by "drop-oldest": frame_id gap of 1
        jpeg = cv2.imencode(".jpg", img, [cv2.IMWRITE_JPEG_QUALITY, 60])[1].tobytes()
        emit(P.JPEG_FRAME, t_us, P.JPEG_HDR.pack(w, h, 60, t_us) + jpeg, fid)
        if fid == 30:
            continue  # DETECTIONS lost: one missing pair
        det = P.DET_HDR.pack(0, len(boxes), w, h) + b"".join(
            P.BOX.pack(b["x1"], b["y1"], b["x2"], b["y2"], b["score"], 0) for b in boxes)
        emit(P.DETECTIONS, t_us, det, fid)
        presence_add(counts, boxes, w, h)
        sent += 1
        if sent % 10 == 0:
            emit(P.PRESENCE_GRID, t_us, P.GRID_HDR.pack(COLS, ROWS, sent, t_us - 1_000_000, w, h)
                 + counts.astype("<u4").tobytes())
        if i % fps == 0:
            emit(P.METRICS, t_us, json.dumps({"synthetic": True, "mode": "full_stream", "fps_processed": fps,
                                              "fps_sent": fps, "uptime_s": t_us / 1e6}).encode())
    (out / "stream.gmtp").write_bytes(b"".join(recs))
    (out / "README.md").write_text(
        "# Synthetic run (generated, not recorded)\n\n"
        f"Made by `python pc/replay.py --make-synthetic {out_dir}`. {n} frames at {fps} fps, 320x240, three box-shaped\n"
        "walkers. On purpose: frame_id 40 is missing (a device drop), frame 30 has no DETECTIONS (a missing pair),\n"
        "walker 0 is not detected on frame 20 (a missed detection). Replay: `python pc/replay.py " + str(out_dir) + "`\n"
        "or `python pc/viewer.py --replay " + str(out_dir) + "`.\n")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("path", help="run directory or .gmtp file")
    ap.add_argument("--speed", type=float, default=0, help="1 = real time, 0 = as fast as possible")
    ap.add_argument("--log", action="store_true", help="also write a new run log under runs/")
    ap.add_argument("--make-synthetic", action="store_true", help="generate the synthetic sample at PATH")
    a = ap.parse_args()
    if a.make_synthetic:
        print("wrote", make_synthetic(a.path))
        return 0
    logger = None
    if a.log:
        from logger import RunLogger
        logger = RunLogger()
    pipe = Pipeline(logger=logger)
    replay(a.path, pipe, a.speed)
    if logger:
        logger.close()
    mv = pipe.movement
    print(json.dumps({"stats": pipe.stats, "device": (pipe.hello or {}).get("device_id"),
                      "presence_frames": (pipe.grid or {}).get("frames"),
                      "movement_crossings": int(mv.counts.sum()) if mv else 0,
                      "movement_observed_s": round(mv.observed_s, 2) if mv else 0,
                      "log_dir": str(logger.dir) if logger else None}, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
