"""The synthetic sample: a made-up session for trying the viewer without a board.

  python pc/main.py make-synthetic samples/synthetic_run

Three box-shaped "walkers" cross a 320 x 240 grey picture. The result is always byte-for-byte
the same (fixed random seed), so tests can compare against the committed copy. Three problems
are added on purpose so the loss counters can be checked:
  - frame_id 40 is missing        (like a frame the board dropped)
  - frame 30 has no DETECTIONS    (a missing pair)
  - walker 0 is missed on frame 20 (a missed detection)
HELLO says device_id "synthetic", so it can never be mistaken for a real recording.
"""
import argparse
import json
from pathlib import Path

import cv2
import numpy as np

from analysis.heatmap import COLS, ROWS, presence_add
from connection import protocol as P

SYNTHETIC_WIDTH, SYNTHETIC_HEIGHT = 320, 240
SYNTHETIC_JPEG_QUALITY = 60
SYNTHETIC_START_US = 1_000_000
WALKER_PATHS = [((-30, 200), (350, 170)), ((330, 120), (-20, 150)), ((150, 245), (190, 90))]
"""Each walker's feet move in a straight line from start to end over the whole run."""
MISSED_DETECTION = (0, 20)
"""(walker, frame index): that walker is not detected in that frame."""
DROPPED_FRAME_ID = 40
FRAME_ID_WITHOUT_DETECTIONS = 30
GRID_EVERY_N_FRAMES = 10


def _walker_box(path, progress):
    """Feet position along the path; the box grows toward the bottom (fake perspective)."""
    (x0, y0), (x1, y1) = path
    feet_x, feet_y = x0 + (x1 - x0) * progress, y0 + (y1 - y0) * progress
    box_height = int(40 + 70 * feet_y / SYNTHETIC_HEIGHT)
    box_width = box_height // 3
    box = [int(feet_x - box_width / 2), int(feet_y - box_height), int(feet_x + box_width / 2), int(feet_y)]
    return feet_x, feet_y, box


def _detected_box(box, score):
    return {"x1": max(box[0], 0), "y1": max(box[1], 0), "x2": min(box[2], SYNTHETIC_WIDTH - 1),
            "y2": min(box[3], SYNTHETIC_HEIGHT - 1), "score": score}


def _render_frame(frame_index, frame_count, rng):
    """Draw one synthetic frame; return (image, detected boxes)."""
    image = np.full((SYNTHETIC_HEIGHT, SYNTHETIC_WIDTH, 3), 90, np.uint8)
    image[SYNTHETIC_HEIGHT // 2:] = 120
    cv2.putText(image, "SYNTHETIC", (8, 20), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (255, 255, 255), 1)
    boxes = []
    for walker, path in enumerate(WALKER_PATHS):
        feet_x, feet_y, box = _walker_box(path, frame_index / (frame_count - 1))
        cv2.rectangle(image, (box[0], box[1]), (box[2], box[3]), (40, 40 + 60 * walker, 160), -1)
        in_view = 0 <= feet_x < SYNTHETIC_WIDTH and 0 <= feet_y - 5 < SYNTHETIC_HEIGHT
        if in_view and (walker, frame_index) != MISSED_DETECTION:
            boxes.append(_detected_box(box, float(0.75 + 0.2 * rng.random())))
    return image, boxes


def _synthetic_hello():
    return {"proto_version": 1, "device_id": "synthetic", "fw_version": "synthetic", "synthetic": True,
            "sensor_pid": "n/a", "grid_cols": COLS, "grid_rows": ROWS, "box_coords": "frame_px",
            "config": {"mode": "full_stream", "frame_size": "QVGA", "jpeg_quality": SYNTHETIC_JPEG_QUALITY,
                       "metrics_interval_ms": 1000, "grid_every_n": GRID_EVERY_N_FRAMES}}


def _detections_payload(boxes):
    header = P.DETECTIONS_HEADER.pack(0, len(boxes), SYNTHETIC_WIDTH, SYNTHETIC_HEIGHT)
    return header + b"".join(P.WIRE_BOX.pack(b["x1"], b["y1"], b["x2"], b["y2"], b["score"], 0) for b in boxes)


class _StreamWriter:
    """Encodes records with consecutive seq numbers."""

    def __init__(self):
        self.records = []

    def emit(self, record_type, t_dev_us, payload, frame_id=0):
        self.records.append(P.encode(record_type, len(self.records), frame_id, t_dev_us, payload))


def _write_readme(out, out_dir, frame_count, fps):
    (out / "README.md").write_text(
        "# Synthetic run (generated, not recorded)\n\n"
        f"Made by `python pc/main.py make-synthetic {out_dir}`. {frame_count} frames at {fps} fps, 320x240, "
        "three box-shaped\nwalkers. On purpose: frame_id 40 is missing (a device drop), frame 30 has no DETECTIONS "
        "(a missing pair),\nwalker 0 is not detected on frame 20 (a missed detection). Replay: "
        f"`python pc/main.py replay {out_dir}`\nor `python pc/main.py viewer --replay {out_dir}`.\n")


def make_synthetic(out_dir, seconds=10, fps=7, seed=1):
    """Write the synthetic run (stream.gmtp + README.md) into out_dir and return its path."""
    rng = np.random.default_rng(seed)
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    stream = _StreamWriter()
    stream.emit(P.HELLO, 0, json.dumps(_synthetic_hello()).encode())
    stream.emit(P.EVENT, 0, json.dumps({"severity": "info", "code": "synthetic_run",
                                        "text": "generated by pc/main.py make-synthetic, not a recording",
                                        "t_event_us": 0}).encode())
    presence = np.zeros((ROWS, COLS), dtype=np.int64)
    frame_count = seconds * fps
    frames_sent = 0
    for frame_index in range(frame_count):
        frame_id = frame_index + 1
        t_us = SYNTHETIC_START_US + frame_index * 1_000_000 // fps
        image, boxes = _render_frame(frame_index, frame_count, rng)
        if frame_id == DROPPED_FRAME_ID:
            continue
        jpeg = cv2.imencode(".jpg", image, [cv2.IMWRITE_JPEG_QUALITY, SYNTHETIC_JPEG_QUALITY])[1].tobytes()
        jpeg_header = P.JPEG_FRAME_HEADER.pack(SYNTHETIC_WIDTH, SYNTHETIC_HEIGHT, SYNTHETIC_JPEG_QUALITY, t_us)
        stream.emit(P.JPEG_FRAME, t_us, jpeg_header + jpeg, frame_id)
        if frame_id == FRAME_ID_WITHOUT_DETECTIONS:
            continue
        stream.emit(P.DETECTIONS, t_us, _detections_payload(boxes), frame_id)
        presence_add(presence, boxes, SYNTHETIC_WIDTH, SYNTHETIC_HEIGHT)
        frames_sent += 1
        if frames_sent % GRID_EVERY_N_FRAMES == 0:
            grid_header = P.GRID_HEADER.pack(COLS, ROWS, frames_sent, t_us - SYNTHETIC_START_US, SYNTHETIC_WIDTH,
                                             SYNTHETIC_HEIGHT)
            stream.emit(P.PRESENCE_GRID, t_us, grid_header + presence.astype("<u4").tobytes())
        if frame_index % fps == 0:
            stream.emit(P.METRICS, t_us, json.dumps({"synthetic": True, "mode": "full_stream", "fps_processed": fps,
                                                     "fps_sent": fps, "uptime_s": t_us / 1e6}).encode())
    (out / "stream.gmtp").write_bytes(b"".join(stream.records))
    _write_readme(out, out_dir, frame_count, fps)
    return out


def main():
    parser = argparse.ArgumentParser(description="Write the synthetic sample session.")
    parser.add_argument("out_dir", help="folder to write, e.g. samples/synthetic_run")
    print("wrote", make_synthetic(parser.parse_args().out_dir))
    return 0
